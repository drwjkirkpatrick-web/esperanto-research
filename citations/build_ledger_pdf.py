#!/usr/bin/env python3
"""Generate ledger.tex (the printable grounded-citation ledger) from citations/ledger.json.

Regenerate + compile:
    cd ~/projects/esperanto-research
    python3 citations/build_ledger_pdf.py
    pdflatex -interaction=nonstopmode -output-directory citations citations/ledger.tex   # twice (hyperref)
Do not hand-edit ledger.tex.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
LEDGER = json.loads((HERE / "ledger.json").read_text(encoding="utf-8"))
SOURCES = LEDGER["sources"]

SPECIALS = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}
UNICODE = {
    "—": "---", "–": "--", "↔": r"$\leftrightarrow$", "→": r"$\rightarrow$",
    "←": r"$\leftarrow$", "×": r"$\times$", "α": r"$\alpha$", "±": r"$\pm$",
    "≥": r"$\geq$", "≤": r"$\leq$", "≈": r"$\approx$", "’": "'", "‘": "`",
    "“": "``", "”": "''", "…": r"\dots{}", "·": r"\textperiodcentered{}",
    "ö": '\\"o', "Ö": '\\"O', "ü": '\\"u', "é": "\\'e", "è": "\\`e",
}

unknown = set()


def tex(s: str) -> str:
    out = []
    for ch in s:
        if ch in UNICODE:
            out.append(UNICODE[ch])
        elif ch in SPECIALS:
            out.append(SPECIALS[ch])
        elif ord(ch) < 128:
            out.append(ch)
        else:
            unknown.add(ch)
            out.append("?")
    return "".join(out)


def entry(src: dict, with_quotes: bool) -> list[str]:
    lines = [
        r"\noindent\textbf{[" + str(src["id"]) + "]} " + tex(src["title"]) + r"\\",
        r"\indent\url{" + src["url"] + "}" + r" \emph{(accessed " + tex(src.get("accessed", "?")) + ")}",
    ]
    quotes = src.get("quotes") or []
    if with_quotes and quotes:
        lines.append(r"\\ \textbf{Verbatim evidence:}")
        for q in quotes:
            lines.append(r"\quad---\,\emph{``" + tex(q["text"]) + "''}")
    return lines


platform = [s for s in SOURCES if s["id"] <= 5]
competitor = [s for s in SOURCES if s["id"] > 5 and "pubmed.ncbi.nlm.nih.gov" not in s["url"]]
literature = [s for s in SOURCES if "pubmed.ncbi.nlm.nih.gov" in s["url"]]
n_quotes = sum(len(s.get("quotes") or []) for s in SOURCES)
q_ids = ", ".join(str(s["id"]) for s in SOURCES if s.get("quotes"))

preamble = r"""% Auto-generated by citations/build_ledger_pdf.py — do not hand-edit.
\documentclass[11pt]{article}
\usepackage{lmodern}
\usepackage[margin=1in]{geometry}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{microtype}
\usepackage{xurl}
\usepackage{xcolor}
\usepackage{enumitem}
\usepackage[colorlinks=true,urlcolor=blue!50!black,linkcolor=black]{hyperref}
\hypersetup{
  pdftitle={esperanto-research: Grounded Citation Ledger},
  pdfsubject={Citation ledger for the OPUS23 | ESPERANTO grounded review (51 registered sources)},
  pdfauthor={Hermes Agent + Walker (grounded-citations workflow)},
  pdfkeywords={grounded-citations, citation ledger, OPUS23, ESPERANTO, Datapunk, evidence quotes}
}
\setlength{\parindent}{0pt}
\setlength{\parskip}{6pt}
\begin{document}

\begin{center}
{\LARGE \textbf{Grounded Citation Ledger}}\\[6pt]
{\large esperanto-research --- a citation-verified review of OPUS23 \textbar{} ESPERANTO}\\[4pt]
{\small Generated 2026-10-30 from \texttt{citations/ledger.json} (grounded-citations workflow)}
\end{center}

\section*{Method}
Every citation in this project's reports resolves to an entry in the mechanical ledger (file
\path{citations/ledger.json}); ids are issued only at retrieval, never from memory.
This document renders the full ledger: \textbf{__NSOURCES__ registered sources},
of which the __NQIDS__ platform sources carry \textbf{__NQUOTES__ verbatim evidence quotes}
--- each machine-checked (``\texttt{sources.py quote -{}-from}'') to appear verbatim,
whitespace- and markup-tolerant, in the fetched page text preserved under \path{extracts/}.
All pages were accessed 2026-10-30.
Quotation text below is reproduced exactly as attached (raw page markup such as \texttt{**}
may be retained inside quotes). Regenerate with \path{citations/build_ledger_pdf.py}.

"""

body = []
body.append(r"\section*{Platform sources --- evidence-carrying}")
for s in platform:
    body.extend(entry(s, with_quotes=True))
    body.append(r"\vspace{4pt}" + "\n")

body.append(r"\section*{Aggregated dossier sources --- competitor verification (03)}")
for s in competitor:
    body.extend(entry(s, with_quotes=False))
    body.append("")

body.append(r"\section*{Aggregated dossier sources --- science-flags literature check (05)}")
for s in literature:
    body.extend(entry(s, with_quotes=False))
    body.append("")

doc = preamble + "\n".join(body) + "\n\\end{document}\n"
doc = (doc.replace("__NSOURCES__", str(len(SOURCES)))
          .replace("__NQUOTES__", str(n_quotes))
          .replace("__NQIDS__", "[" + q_ids + "]"))

(HERE / "ledger.tex").write_text(doc, encoding="utf-8")
print(f"wrote {HERE / 'ledger.tex'}: {len(SOURCES)} sources, {n_quotes} quotes on ids [{q_ids}]")
if unknown:
    print("UNMAPPED UNICODE CHARS (rendered as '?'):", {hex(ord(c)): c for c in sorted(unknown)})
